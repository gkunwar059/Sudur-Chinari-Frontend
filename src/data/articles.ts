export function getFeaturedArticles(): Article[] {
  return ARTICLES.filter(a => a.featured).slice(0, 4);
}

export function getBreakingArticles(): Article[] {
  return ARTICLES.filter(a => a.breaking).slice(0, 3);
}

export function getLatestArticles(count = 6): Article[] {
  return [...ARTICLES].sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()).slice(0, count);
}

export function getPopularArticles(count = 5): Article[] {
  return ARTICLES.filter(a => a.popular).sort((a, b) => (b.views ?? 0) - (a.views ?? 0)).slice(0, count);
}

export function getArticlesByDistrict(districtSlug: string, count = 6): Article[] {
  return ARTICLES.filter(a => a.district?.slug === districtSlug).slice(0, count);
}

export function getArticlesByCategory(categorySlug: string, count = 6): Article[] {
  return ARTICLES.filter(a => a.category.slug === categorySlug).slice(0, count);
}

export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find(a => typeof a.slug === 'string' ? a.slug === slug : (a.slug.ne === slug || a.slug.en === slug));
}
